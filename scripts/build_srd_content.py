def transform_condition(up: dict) -> dict:
    return {
        "slug": up.get("slug", ""),
        "name": up.get("name", ""),
        "desc": _strip_md(up.get("desc") or ""),
        "actions": [{
            "id": "effect",
            "name": up.get("name", ""),
            "desc": _strip_md(up.get("desc") or "")[:300],
            "category": "passive",
        }],
        "system": "dnd5e",
        "scope": "global",
        "source": "srd",
        "_attribution": ATTRIBUTION,
    }


def transform_magicitem(up: dict) -> dict:
    """Open5e magic items lack structured charge / damage fields, so we ship
    them as `type='magic'` with empty actions. GMs can extend via the homebrew
    UI to add specific Action entries."""
    return {
        "slug": up.get("slug", ""),
        "name": up.get("name", ""),
        "type": "magic",
        "rarity": (up.get("rarity") or "common").lower(),
        "attunement": bool(up.get("requires_attunement") and
                           (up.get("requires_attunement") or "").lower() not in ("", "no")),
        "weight": "",
        "cost": "",
        "desc": _strip_md(up.get("desc") or ""),
        "properties": {"category": up.get("type", "") or ""},
        "actions": [],
        "system": "dnd5e",
        "scope": "global",
        "source": "srd",
        "_attribution": ATTRIBUTION,
    }


def transform_weapon(up: dict) -> dict:
    props = {
        "damage": (up.get("damage_dice") or "") + (
            f" {up.get('damage_type','')}" if up.get("damage_type") else ""
        ),
        "category": up.get("category", "") or "",
        "properties": up.get("properties") or [],
    }
    return {
        "slug": up.get("key") or up.get("slug") or up.get("name", "").lower().replace(" ", "-"),
        "name": up.get("name", ""),
        "type": "weapon",
        "rarity": "common",
        "attunement": False,
        "weight": str(up.get("weight", "")) + (" lb" if up.get("weight") else ""),
        "cost": str(up.get("cost", "")) or "",
        "desc": "",
        "properties": props,
        "actions": [],
        "system": "dnd5e",
        "scope": "global",
        "source": "srd",
        "_attribution": ATTRIBUTION,
    }


def transform_armor(up: dict) -> dict:
    return {
        "slug": up.get("key") or up.get("slug") or up.get("name", "").lower().replace(" ", "-"),
        "name": up.get("name", ""),
        "type": "armor",
        "rarity": "common",
        "attunement": False,
        "weight": str(up.get("weight", "")) + (" lb" if up.get("weight") else ""),
        "cost": str(up.get("cost", "")) or "",
        "desc": "",
        "properties": {
            "category": up.get("category", "") or "",
            "ac_base": up.get("base_ac", 0),
            "stealth_disadvantage": bool(up.get("stealth_disadvantage")),
        },
        "actions": [],
        "system": "dnd5e",
        "scope": "global",
        "source": "srd",
        "_attribution": ATTRIBUTION,
    }


# ── Type dispatch table ──────────────────────────────────────────────────────
# Maps the on-disk content directory → (Open5e endpoint, Pydantic model,
# transformer). Some Open5e endpoints (magicitems / weapons / armor) all
# write into the same ``items/`` directory.
ENDPOINTS: dict[str, list[tuple[str, type, callable]]] = {
    "spells":      [("spells",      Spell,      transform_spell)],
    "monsters":    [("monsters",    Monster,    transform_monster)],
    "feats":       [("feats",       Feat,       transform_feat)],
    "backgrounds": [("backgrounds", Background, transform_background)],
    "conditions":  [("conditions",  Condition,  transform_condition)],
    "items": [
        ("magicitems", Item, transform_magicitem),
        ("weapons",    Item, transform_weapon),
        ("armor",      Item, transform_armor),
    ],
}


# ── Pipeline ─────────────────────────────────────────────────────────────────
def write_record(record: dict, *, type_dir: str, model: type) -> tuple[bool, str]:
    """Validate then atomically write one record. Returns ``(ok, message)``."""
    slug = _sanitize_slug(record.get("slug") or "")
    if not slug:
        return False, f"invalid slug: {record.get('slug')!r}"
    # Update the record so the saved file shows the sanitized form.
    record["slug"] = slug
    try:
        validated = model.model_validate(record).model_dump(by_alias=True)
    except Exception as e:
        return False, f"validation failed: {e}"
    out_dir = DEST_ROOT / type_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    final = out_dir / f"{slug}.json"
    tmp = out_dir / f".{slug}.json.tmp"
    tmp.write_text(json.dumps(validated, indent=2, ensure_ascii=False), encoding="utf-8")
    os.replace(tmp, final)
    return True, str(final)


def _is_srd(upstream: dict) -> bool:
    """Open5e tags SRD records with document__slug == 'wotc-srd'. Some
    response shapes embed the document object instead — handle both."""
    doc_slug = upstream.get("document__slug")
    if not doc_slug:
        doc = upstream.get("document") or {}
        if isinstance(doc, dict):
            doc_slug = doc.get("slug")
    return (doc_slug or "").lower() == SRD_DOCUMENT_SLUG


def build(types: list[str], *, dry_run: bool, include_all: bool) -> dict[str, dict[str, int]]:
    summary: dict[str, dict[str, int]] = {}
    for type_dir in types:
        if type_dir not in ENDPOINTS:
            print(f"  skip unknown type: {type_dir}")
            continue
        summary[type_dir] = {"ok": 0, "skipped": 0, "filtered_non_srd": 0}
        for endpoint, model, transformer in ENDPOINTS[type_dir]:
            print(f"[{type_dir}] fetching {endpoint}...")
            try:
                raw = fetch_all(endpoint)
            except Exception as e:
                print(f"  FAIL: {e}")
                continue
            for up in raw:
                if not include_all and not _is_srd(up):
                    summary[type_dir]["filtered_non_srd"] += 1
                    continue
                record = transformer(up)
                if dry_run:
                    summary[type_dir]["ok"] += 1
                    continue
                ok, msg = write_record(record, type_dir=type_dir, model=model)
                if ok:
                    summary[type_dir]["ok"] += 1
                else:
                    summary[type_dir]["skipped"] += 1
                    print(f"  skip {up.get('slug','?')}: {msg}")
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--type",
        default=",".join(ENDPOINTS.keys()),
        help="comma-separated content types to build (default: all)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="fetch and transform, but don't write any files",
    )
    parser.add_argument(
        "--include-all",
        action="store_true",
        help="include every Open5e document, not just the WotC SRD baseline. "
        "Default is SRD-only because that's the licensing perimeter the rest "
        "of the codebase cites; only enable if you've verified the third-party "
        "licenses for your deployment.",
    )
    args = parser.parse_args()
    types = [t.strip() for t in args.type.split(",") if t.strip()]

    print(f"Open5e base : {OPEN5E_BASE}")
    print(f"Output root : {DEST_ROOT}")
    print(f"Types       : {types}")
    print(f"Dry-run     : {args.dry_run}")
    print(f"Scope       : {'ALL Open5e' if args.include_all else 'SRD only (document__slug=wotc-srd)'}\n")

    if not args.dry_run:
        print(
            "⚠  WARNING: writing to the live content dir OVERWRITES each file\n"
            "   wholesale. The shipped JSONs carry curated fields this script\n"
            "   does NOT regenerate (actions[].area, upcast, damage scaling,\n"
            "   action gating — see the module docstring). A blind re-run\n"
            "   silently drops them and breaks AoE placement + upcast tests.\n"
            "   Prefer --dry-run / a scratch DEST_ROOT + a hand-merged diff.\n"
        )

    summary = build(types, dry_run=args.dry_run, include_all=args.include_all)

    print("\n-- Summary -----------------------------------------")
    for type_dir, counts in summary.items():
        print(f"  {type_dir:<14} ok={counts['ok']:<5} "
              f"skipped={counts['skipped']:<3} "
              f"non-srd-filtered={counts['filtered_non_srd']}")
    print("----------------------------------------------------")
    return 0


if __name__ == "__main__":
    sys.exit(main())
